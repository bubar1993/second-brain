-- Second Brain GF – Backup settimanale su Google Drive (cartella BRAIN/Backup)
-- Ogni domenica notte pg_cron chiama la funzione "backup", che salva:
--   brain-dati-AAAA-MM-GG.json.gz     → tutti i dati (backup_export)
--   brain-struttura-AAAA-MM-GG.sql    → la struttura (backup_schema, stesso metodo del gestionale G&C)
--   Foto/…                            → solo le foto nuove (registro in backup_foto)
-- L'esito va in backup_registro: l'app avvisa nella schermata Oggi se qualcosa non va.
-- La chiave "backup_token" sta nel Vault (creata a parte, non in questo file).

create extension if not exists pg_net with schema extensions;

-- ---------------------------------------------------------------
-- Registro dei backup (leggibile dall'app)
-- ---------------------------------------------------------------
create table public.backup_registro (
  id           bigint generated always as identity primary key,
  eseguito_il  timestamptz not null default now(),
  ok           boolean not null,
  dettagli     jsonb,
  errore       text
);
alter table public.backup_registro enable row level security;
revoke all on public.backup_registro from anon, authenticated;
grant select on public.backup_registro to authenticated;
create policy "lettura per l'app" on public.backup_registro
  for select to authenticated using ((select auth.uid()) is not null);

-- Foto già copiate su Drive (solo la funzione di backup la usa)
create table public.backup_foto (
  percorso    text primary key,
  drive_id    text not null,
  copiata_il  timestamptz not null default now()
);
alter table public.backup_foto enable row level security;
revoke all on public.backup_foto from anon, authenticated;

-- ---------------------------------------------------------------
-- Esportazione di tutti i dati
-- ---------------------------------------------------------------
create function public.backup_export()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  r record;
  righe jsonb;
  risultato jsonb := '{}'::jsonb;
begin
  for r in select tablename from pg_catalog.pg_tables where schemaname = 'public' order by 1 loop
    execute format('select coalesce(jsonb_agg(to_jsonb(t)), ''[]''::jsonb) from public.%I t', r.tablename) into righe;
    risultato := risultato || jsonb_build_object(r.tablename, righe);
  end loop;
  return risultato;
end;
$$;
revoke all on function public.backup_export() from public, anon, authenticated;
grant execute on function public.backup_export() to service_role;

-- ---------------------------------------------------------------
-- Struttura del database come script SQL (adattata dal gestionale G&C, migrazione 048)
-- ---------------------------------------------------------------
create function public.backup_schema()
returns text
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $$
declare
  parts text[] := array[]::text[];
  tb record; r record; g record;
  cols text;
begin
  parts := array_append(parts, '-- Struttura del database Second Brain (Supabase vgurncqvgulldolhetyr)');
  parts := array_append(parts, '-- Generata il ' || to_char(now() at time zone 'Europe/Zurich', 'YYYY-MM-DD HH24:MI') || ' (ora svizzera).');
  parts := array_append(parts, '-- Serve a ricostruire il database da zero in un progetto Supabase NUOVO e VUOTO:');
  parts := array_append(parts, '--   1) eseguire questo file nell''SQL Editor;  2) importare i dati dal brain-dati-AAAA-MM-GG.json.gz.');
  parts := array_append(parts, 'set check_function_bodies = off;');
  parts := array_append(parts, '');

  parts := array_append(parts, '-- ===== Estensioni');
  for r in
    select e.extname, n.nspname from pg_extension e join pg_namespace n on n.oid = e.extnamespace
    where e.extname in ('uuid-ossp', 'pgcrypto', 'pg_cron', 'pg_net') order by 1
  loop
    parts := array_append(parts, case when r.nspname = 'pg_catalog'
      then format('create extension if not exists %I;', r.extname)
      else format('create extension if not exists %I with schema %I;', r.extname, r.nspname) end);
  end loop;

  parts := array_append(parts, '');
  parts := array_append(parts, '-- ===== Tabelle');
  for tb in
    select c.oid, c.relname, n.nspname, c.relrowsecurity
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind in ('r', 'p')
    order by c.relname
  loop
    select string_agg(format('  %I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
        case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
             when a.attidentity = 'a' then ' generated always as identity'
             when a.attidentity = 'd' then ' generated by default as identity'
             when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid)
             else '' end,
        case when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum)
      into cols
    from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
    where a.attrelid = tb.oid and a.attnum > 0 and not a.attisdropped;
    parts := array_append(parts, format(E'create table %I.%I (\n%s\n);', tb.nspname, tb.relname, coalesce(cols, '')));
    if tb.relrowsecurity then parts := array_append(parts, format('alter table %I.%I enable row level security;', tb.nspname, tb.relname)); end if;
  end loop;

  parts := array_append(parts, '');
  parts := array_append(parts, '-- ===== Vincoli');
  for r in
    select con.conrelid::regclass::text rel, con.conname, pg_get_constraintdef(con.oid) def
    from pg_constraint con join pg_class c on c.oid = con.conrelid join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and con.contype in ('p', 'u', 'c', 'x', 'f')
    order by case when con.contype = 'f' then 1 else 0 end, case con.contype when 'p' then 0 else 1 end, 1, 2
  loop
    parts := array_append(parts, format('alter table %s add constraint %I %s;', r.rel, r.conname, r.def));
  end loop;

  parts := array_append(parts, '');
  parts := array_append(parts, '-- ===== Funzioni');
  for r in
    select pg_get_functiondef(p.oid) def
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.prokind in ('f', 'p')
      and not exists (select 1 from pg_depend dp where dp.objid = p.oid and dp.deptype = 'e')
    order by p.proname, p.oid
  loop
    parts := array_append(parts, rtrim(r.def) || ';');
  end loop;

  parts := array_append(parts, '');
  parts := array_append(parts, '-- ===== Indici');
  for r in
    select pg_get_indexdef(i.indexrelid) def
    from pg_index i join pg_class c on c.oid = i.indrelid join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public'
      and not exists (select 1 from pg_constraint con where con.conindid = i.indexrelid)
    order by 1
  loop
    parts := array_append(parts, r.def || ';');
  end loop;

  parts := array_append(parts, '');
  parts := array_append(parts, '-- ===== Trigger');
  for r in
    select pg_get_triggerdef(tg.oid) def
    from pg_trigger tg join pg_class c on c.oid = tg.tgrelid join pg_namespace n on n.oid = c.relnamespace
    where not tg.tgisinternal and n.nspname = 'public'
    order by c.relname, tg.tgname
  loop
    parts := array_append(parts, r.def || ';');
  end loop;

  parts := array_append(parts, '');
  parts := array_append(parts, '-- ===== Regole di sicurezza (RLS)');
  for r in select * from pg_policies where schemaname in ('public', 'storage') order by schemaname, tablename, policyname loop
    parts := array_append(parts, format('create policy %I on %I.%I as %s for %s to %s%s%s;',
      r.policyname, r.schemaname, r.tablename, r.permissive, r.cmd,
      (select string_agg(case when x = 'public' then 'public' else quote_ident(x) end, ', ') from unnest(r.roles) x),
      case when r.qual is not null then ' using (' || r.qual || ')' else '' end,
      case when r.with_check is not null then ' with check (' || r.with_check || ')' else '' end));
  end loop;

  parts := array_append(parts, '');
  parts := array_append(parts, '-- ===== Permessi');
  for r in
    select c.oid::regclass::text obj, c.relacl acl, c.relowner own
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind in ('r', 'p', 'v', 'm') and c.relacl is not null
    order by 1
  loop
    parts := array_append(parts, format('revoke all on table %s from public, anon, authenticated, service_role;', r.obj));
    for g in select case when x.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(x.grantee)) end gr,
                    string_agg(x.privilege_type, ', ' order by x.privilege_type) privs
             from aclexplode(r.acl) x where x.grantee <> r.own group by 1 order by 1 loop
      parts := array_append(parts, format('grant %s on table %s to %s;', g.privs, r.obj, g.gr));
    end loop;
  end loop;
  for r in
    select p.oid::regprocedure::text obj, p.proacl acl, p.proowner own
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.prokind in ('f', 'p') and p.proacl is not null
      and not exists (select 1 from pg_depend dp where dp.objid = p.oid and dp.deptype = 'e')
    order by 1
  loop
    parts := array_append(parts, format('revoke all on function %s from public, anon, authenticated, service_role;', r.obj));
    for g in select case when x.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(x.grantee)) end gr
             from aclexplode(r.acl) x where x.grantee <> r.own and x.privilege_type = 'EXECUTE' group by 1 order by 1 loop
      parts := array_append(parts, format('grant execute on function %s to %s;', r.obj, g.gr));
    end loop;
  end loop;

  parts := array_append(parts, '');
  parts := array_append(parts, '-- ===== EXTRA SUPABASE (Storage e programmazioni)');
  for r in select * from storage.buckets order by id loop
    parts := array_append(parts, format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %L, %L, %L) on conflict (id) do nothing;',
      r.id, r.name, r.public, r.file_size_limit, r.allowed_mime_types));
  end loop;
  parts := array_append(parts, '-- Attenzione: le programmazioni contengono l''indirizzo del progetto attuale; la chiave backup_token va ricreata nel Vault.');
  for r in select jobname, schedule, command from cron.job order by jobname loop
    parts := array_append(parts, format('select cron.schedule(%L, %L, %L);', r.jobname, r.schedule, r.command));
  end loop;

  return array_to_string(parts, E'\n') || E'\n';
end;
$$;
revoke all on function public.backup_schema() from public, anon, authenticated;
grant execute on function public.backup_schema() to service_role;

